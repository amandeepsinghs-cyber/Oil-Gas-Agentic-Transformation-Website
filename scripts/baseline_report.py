    md = []
    md.append("# Phase 0 Baseline Report: 33 Oil & Gas Personas")
    md.append("")
    md.append("> **Source of Truth**: Grounded directly in generated data files (`data/personas/index.json`, `data/personas/Pxx.json`, and `working_deck/data/matrix_33.js`).")
    md.append("> Generated by `scripts/baseline_report.py`.")
    md.append("")
    md.append("---")
    md.append("")
    md.append("## 1 · Executive Baseline Metrics")
    md.append("")
    md.append("| Metric | Count / Value | Data Source | Notes |")
    md.append("|---|:---:|---|---|")
    md.append(f"| **Total Personas** | **{persona_count}** | `data/personas/index.json` | Full standardized industry roster (P01–P33) |")
    md.append(f"| **Core 20 Dashboard Personas** | **{sum(1 for p in index_data if p.get('core20'))}** | `index.json` (`core20: true`) | Primary executive presentation cohort |")
    md.append(f"| **Extended Ecosystem Personas** | **{sum(1 for p in index_data if not p.get('core20'))}** | `index.json` (`core20: false`) | Extended specialist taxonomy (P21–P33) |")
    md.append(f"| **Total Workflows / Actions** | **{total_actions}** | Sum across `data/personas/Pxx.json` | 30 roles × 15 + 3 roles × 16 (P04, P05, P07) |")
    md.append(f"| **Total Agents (`index.json` sum)** | **{agents_index_sum}** | `sum(p.agentCount)` | Sum of `agentCount` across all 33 persona index entries |")
    md.append(f"| **Total Agents (`Pxx.json` arrays)** | **{agents_detail_count}** | `sum(len(p.agents))` | Exact sum of parsed agent definitions in detail files |")
    md.append(f"| **Board Cells (`matrix_33.js`)** | **{matrix_cells}** | `window.ENTERPRISE_MATRIX_META.cells` | Ragged 33-row operational matrix |")
