    md.append("| Sub-Segment | Roles | Workflows | Agents | Value (₹ Cr) | Roles |")
    md.append("|---|:---:|:---:|:---:|:---:|---|")
    sorted_segs = sorted(segment_stats.items(), key=lambda kv: (-kv[1]["personas"], -kv[1]["totalCr"]))
    for seg, st in sorted_segs:
        p_list = ", ".join(st["pids"])
        md.append(f"| **{seg}** | {st['personas']} | {st['actions']} | {st['agents']} | ₹{st['totalCr']:,.1f} Cr | {p_list} |")
    md.append(f"| **Total** | **{persona_count}** | **{total_actions}** | **{agents_detail_count}** | **₹{grand_total:,.1f} Cr** | |")
    md.append("")
    md.append("---")
    md.append("")
    md.append("## 4 · Full Persona Inventory (33 Roles)")
    md.append("")
