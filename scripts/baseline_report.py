#!/usr/bin/env python3
"""
baseline_report.py — Compute data baseline and generate persona_research/BASELINE_33.md

Computes from the data (not slide prose):
  - Persona count (33)
  - Per-segment and per-group counts
  - Total actions (498)
  - Total agents:
      * sum of agentCount in data/personas/index.json (234)
      * count of agents arrays across data/personas/Pxx.json (234)
  - Cells in working_deck/data/matrix_33.js (498)
  - Owner split of cells (agentic/system/human)
  - Rs Cr total per lever (human, asset, risk, recovery) and grand total
  - Comprehensive reconciliation of "232 vs 234" agents with file:line citations

Usage:
    python3 scripts/baseline_report.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = REPO_ROOT / "data" / "personas"
INDEX_JSON_PATH = DATA_DIR / "index.json"
MATRIX_JS_PATH = REPO_ROOT / "working_deck" / "data" / "matrix_33.js"
REPORT_MD_PATH = REPO_ROOT / "persona_research" / "BASELINE_33.md"


def load_matrix_via_node() -> tuple[list[dict], dict]:
    """Load matrix_33.js via node with a global.window shim."""
    node_cmd = (
        'global.window = {}; '
        f'require("{MATRIX_JS_PATH.as_posix()}"); '
        'console.log(JSON.stringify({ '
        '  data: window.ENTERPRISE_MATRIX_DATA, '
        '  meta: window.ENTERPRISE_MATRIX_META '
        '}));'
    )
    res = subprocess.run(
        ["node", "-e", node_cmd],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    parsed = json.loads(res.stdout)
    return parsed["data"], parsed["meta"]


def generate_baseline():
    # 1. Load data/personas/index.json
    with open(INDEX_JSON_PATH, "r", encoding="utf-8") as f:
        index_data = json.load(f)

    persona_count = len(index_data)
    agents_index_sum = sum(p.get("agentCount", 0) for p in index_data)

    # 2. Inspect individual Pxx.json files
    total_actions = 0
    agents_detail_count = 0
    actions_per_persona = {}
    agents_per_persona = {}
    ragged_personas = {}

    for p in index_data:
        pid = p["id"]
        p_path = DATA_DIR / f"{pid}.json"
        with open(p_path, "r", encoding="utf-8") as pf:
            p_data = json.load(pf)
        n_acts = len(p_data.get("actions", []))
        n_agents = len(p_data.get("agents", []))
        total_actions += n_acts
        agents_detail_count += n_agents
        actions_per_persona[pid] = n_acts
        agents_per_persona[pid] = n_agents
        if n_acts != 15:
            ragged_personas[pid] = n_acts

    # 3. Load matrix_33.js data
    matrix_rows, matrix_meta = load_matrix_via_node()
    matrix_cells = matrix_meta["cells"]
    owners = matrix_meta["owners"]

    # 4. Levers computation
    lever_human = round(sum(r["value"]["human"] for r in matrix_rows if r.get("value")), 1)
    lever_asset = round(sum(r["value"]["asset"] for r in matrix_rows if r.get("value")), 1)
    lever_risk = round(sum(r["value"]["risk"] for r in matrix_rows if r.get("value")), 1)
    lever_recov = round(sum(r["value"]["recov"] for r in matrix_rows if r.get("value")), 1)
    grand_total = round(sum(r["value"]["total"] for r in matrix_rows if r.get("value")), 1)
    estate_cr = matrix_meta.get("estateCr", round(grand_total))

    # 5. Group and segment aggregations
    group_stats = defaultdict(lambda: {"personas": 0, "actions": 0, "agents": 0, "totalCr": 0.0, "pids": []})
    for r in matrix_rows:
        grp = r.get("groupLabel", r.get("group", "Other"))
        pid = r["id"]
        group_stats[grp]["personas"] += 1
        group_stats[grp]["actions"] += len(r.get("actions", []))
        group_stats[grp]["agents"] += r.get("agentCount", 0)
        group_stats[grp]["totalCr"] += r["value"]["total"] if r.get("value") else 0.0
        group_stats[grp]["pids"].append(pid)

    segment_stats = defaultdict(lambda: {"personas": 0, "actions": 0, "agents": 0, "totalCr": 0.0, "pids": []})
    for r in matrix_rows:
        seg = r.get("segment", "Unknown")
        pid = r["id"]
        segment_stats[seg]["personas"] += 1
        segment_stats[seg]["actions"] += len(r.get("actions", []))
        segment_stats[seg]["agents"] += r.get("agentCount", 0)
        segment_stats[seg]["totalCr"] += r["value"]["total"] if r.get("value") else 0.0
        segment_stats[seg]["pids"].append(pid)

