    md.append(f"| **Uptime (Asset Capital)** | Avoided deferment hours / equipment downtime | ₹{lever_asset:,.1f} Cr | {lever_asset / grand_total * 100:.1f}% | Critical-path drilling, compression & refining uptime saved |")
    md.append(f"| **Integrity (Asset Risk)** | `frequency * consequence * alpha * beta` | ₹{lever_risk:,.1f} Cr | {lever_risk / grand_total * 100:.1f}% | Process safety, well integrity, and pipeline containment risk reduction |")
    md.append(f"| **Recovery (Resource Upside)** | `bbl * margin` | ₹{lever_recov:,.1f} Cr | {lever_recov / grand_total * 100:.1f}% | Direct barrel yield optimization and subsurface recovery |")
    md.append(f"| **Grand Total** | Sum of row values | **₹{grand_total:,.1f} Cr** | **100.0%** | **Rounded Estate: ₹{estate_cr:,} Cr / yr** |")
    md.append("")
    md.append("---")
    md.append("")
    md.append("## 2 · Value-Chain Groups Breakdown")
    md.append("")
    md.append("Aggregated into the 6 value-chain groups matching the presentation filter chips and `matrix_33.js`:")
    md.append("")
